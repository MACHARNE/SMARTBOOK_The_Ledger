import assert from "node:assert/strict";
import { consumeAuthCallback, loginPortal } from "../../fb091d/auth-flow.js";
let path;
let calls=[];
const session={access_token:"fixture-token",user:{id:"fixture"}};
const ok=async (name, input)=>{calls.push([name,input]);return {data:{session},error:null};};
const client={auth:{setSession:value=>ok("implicit",value),verifyOtp:value=>ok("otp",value),exchangeCodeForSession:value=>ok("pkce",value),getSession:()=>ok("existing")}};
const history={replaceState(_state,_title,value){path=value;}};
const run=async url=>{const location=new URL(url,"https://example.test");return consumeAuthCallback(client,location,history);};
const implicit=await run("/auth/invite#access_token=fixture-access&refresh_token=fixture-refresh&type=invite");
assert.equal(implicit.requiresPassword,true);assert.equal(path,"/auth/invite");
assert.deepEqual(calls[0],["implicit",{access_token:"fixture-access",refresh_token:"fixture-refresh"}]);
await run("/auth/invite?token_hash=fixture-hash&type=invite");assert.equal(calls.at(-1)[0],"otp");
await run("/auth/callback?code=fixture-code");assert.equal(calls.at(-1)[0],"pkce");
assert.equal((await run("/login#access_token=x&refresh_token=y&type=recovery")).recovery,true);
await assert.rejects(run("/auth/invite?error_description=expired"),/expired/);
assert.equal(loginPortal({kind:"platform_admin",role:"admin"}),"/admin/login");
assert.equal(loginPortal({kind:"platform_admin",role:"super_admin"}),"/super-admin/login");
assert.equal(loginPortal({kind:"company_user"}),"/login");
console.log("Passed: implicit invitations, token-hash callbacks, legacy PKCE links, recovery, expired links, token cleanup, and portal routing.");
